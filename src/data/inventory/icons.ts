function buildDataIdIconFallbacks(): Record<string, IconName> {
  const fallbacks: Record<string, IconName> = {}

  for (const [icon, ids] of Object.entries(DATA_ICON_ID_FALLBACKS) as [IconName, readonly string[]][]) {
    for (const id of ids) {
      if (fallbacks[id]) {
        throw new Error(`Duplicate data icon fallback id: ${id}`)
      }
      fallbacks[id] = icon
    }
  }

  return fallbacks
}

