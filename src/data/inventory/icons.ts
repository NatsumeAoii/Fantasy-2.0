function shouldUseDataIdIconFallback(id: string, type: string | undefined, category: string | undefined): boolean {
  if (!DATA_ID_ICON_FALLBACKS[id]) return false
  if (!CONTEXTUAL_DATA_ID_FALLBACKS.has(id)) return true
  if (!type && !category) return true

  return [type, category].some((context) => context !== undefined && DATA_ID_FALLBACK_CONTEXTS.has(context))
}

function textMatchesKeyword(text: string, keyword: string): boolean {
  const normalizedKeyword = normalizeIconText(keyword)
  if (!normalizedKeyword) return false

  if (normalizedKeyword.includes(' ')) {
    return text.includes(normalizedKeyword)
  }

  const tokens = text.split(' ')
  return tokens.includes(normalizedKeyword) || tokens.includes(`${normalizedKeyword}s`)
}

/**
 * Resolve the closest registered icon name for a generated or explicit entry.
 * Explicit registered icons win; semantic text is used next; type fallbacks
 * keep unknown entries visually stable.
 */
export function resolveIconName(input: IconResolveInput): IconName {
  if (hasRegisteredIcon(input.explicitIcon)) {
    return input.explicitIcon
  }

  const type = fallbackKey(input.type)
  const category = fallbackKey(input.category)
  if (category && CATEGORY_FIRST_FALLBACKS.has(category) && CATEGORY_FALLBACKS[category]) {
    return CATEGORY_FALLBACKS[category]
  }
  if (type && CATEGORY_FIRST_FALLBACKS.has(type) && CATEGORY_FALLBACKS[type]) {
    return CATEGORY_FALLBACKS[type]
  }

  const id = dataIdKey(input.id)
  if (id && shouldUseDataIdIconFallback(id, type, category)) {
    return DATA_ID_ICON_FALLBACKS[id]
  }

  const text = normalizeIconText(
    [
      input.id,
      input.name,
      input.title,
      input.category,
      input.type,
      input.description,
      input.desc,
      input.effect,
      input.benefit,
      input.mechanicalEffect,
      input.variant?.name,
      input.variant?.description,
      input.variant?.desc,
      ...(input.tags ?? []),
      ...flattenMetadataValue(input.metadata),
    ]
      .filter((part): part is string => typeof part === 'string' && part.length > 0)
      .join(' '),
  )

  if (text) {
    for (const rule of SEMANTIC_ICON_RULES) {
      if (rule.keywords.some((keyword) => textMatchesKeyword(text, keyword))) {
        return rule.icon
      }
    }
  }

  return (type && CATEGORY_FALLBACKS[type]) || (category && CATEGORY_FALLBACKS[category]) || FALLBACK_ICON_NAME
}

