function normalizeIconText(value: string): string {
  return value
    .normalize('NFKD')
    .replace(/[''`]/g, ' ')
    .replace(/[^a-zA-Z0-9]+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
    .toLowerCase()
}

function flattenMetadataValue(value: unknown): string[] {
  if (value === null || value === undefined) return []
  if (Array.isArray(value)) return value.flatMap(flattenMetadataValue)
  if (typeof value === 'object') {
    return Object.values(value as Record<string, unknown>).flatMap(flattenMetadataValue)
  }
  return [String(value)]
}

function hasRegisteredIcon(name: string | null | undefined): name is IconName {
  return !!name && Object.prototype.hasOwnProperty.call(ICON_REGISTRY, name)
}

function fallbackKey(value: string | null | undefined): string | undefined {
  const normalized = value ? normalizeIconText(value).toUpperCase() : ''
  return normalized || undefined
}

function dataIdKey(value: string | null | undefined): string | undefined {
  const normalized = value ? normalizeIconText(value).replace(/\s+/g, '_') : ''
  return normalized || undefined
}

