export type SpellSchool = 'Destruction' | 'Warding' | 'Summoning' | 'Scrying' | 'Enchantment' | 'Illusion' | 'Death Magic' | 'Alchemy';

export type SpellLevel = 'Petty' | 'Novice' | 'Adept' | 'Master';

export type SpellRarity = 'Common' | 'Uncommon' | 'Rare' | 'Legendary';

export type SpellComponentType = 'verbal' | 'somatic' | 'material' | 'focus' | 'blood';

export interface SpellComponent {
    type: SpellComponentType;
    desc: string;
}

export type ResistType = 'willpower' | 'fortitude' | 'reflex' | 'none';

/**
 * The mechanical outcome of casting a spell, including damage,
 * healing, or status effects applied to targets.
 */
export interface SpellEffect {
  name: string;
  description: string;
}

/**
 * A magical ability that consumes mana to produce a specific effect.
 * Spells belong to one of eight arcane schools and are tiered into
 * four power levels: Petty, Novice, Adept, and Master.
 */
export interface Spell {
  id: string;
  name: string;
  school: SpellSchool;
  level: SpellLevel;
  rarity: SpellRarity;
  castingTime: string;
  manaCost: number;
  hpCost: number;
  damage: number | null;
  damageType: string | null;
  deliveryType: string;
  range: string;
  effect: SpellEffect | null;
  effectDuration: string | null;
  baseCooldown: number;
  baseDuration: number;
  baseRange: number;
  baseCastTime: number;
  description: string;
  components: SpellComponent[];
  resistCheck: ResistType;
  counterSchool: SpellSchool | null;
}

